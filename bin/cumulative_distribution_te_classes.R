#!/usr/bin/env Rscript
# ------------------------------------------------------------------------------
# Cumulative distance distributions between KMT2B peaks and TE classes
# ------------------------------------------------------------------------------
# Purpose:
#   Compute cumulative distance distributions from KMT2B peak categories to the
#   nearest TE features, including LINE/L1, SINE, LTR, and ERV subsets, then
#   produce ECDF plots and Wilcoxon rank-sum tests between classes.
#
# This script is based on the older analysis logic found in the temporary
# project scripts under assets/tmp, especially TE_distance_extimation.R.
# ------------------------------------------------------------------------------

suppressPackageStartupMessages({
  library(ggplot2)
  library(RColorBrewer)
})

options(scipen = 999)

# ------------------------------ USER SETTINGS ------------------------------
# Adjust these paths to match your local structure.
ROOT <- getwd()
SRC_DIST <- file.path(ROOT, "pipelines/downstream_multiomic/bin/distance_functions.R")

# Input files
# - REPEATMASK_FILE: RepeatMasker annotation in UCSC-style BED-like format.
#   Download it from the UCSC RepeatMasker track or a compatible source before running.
# - PEAKS_DIR: directory containing the KMT2B peak BED files generated by the
#   previous ChIP-seq/post-processing pipeline steps.
REPEATMASK_FILE <- file.path(ROOT, "assets/rmsk.txt")
PEAKS_DIR <- file.path(ROOT, "outs/CHiP_postprocessing_line1_dist")
OUTDIR <- file.path(ROOT, "outs/cumulative_te_dist")

# Expected peak files in PEAKS_DIR
PEAK_FILES <- c(
  "K4me3_distal_CpG_minus_Double_KO_vs_F_F.bed",
  "K4me3_distal_CpG_plus_Double_KO_vs_F_F.bed",
  "K4me3_proximal_CpG_minus_Double_KO_vs_F_F.bed",
  "K4me3_proximal_CpG_plus_Double_KO_vs_F_F.bed"
)

# ------------------------------------------------------------------------------
# Helper functions
# ------------------------------------------------------------------------------

source(SRC_DIST)

te_group_colors <- c(
  "K4me3_distal_CpG_minus_Double_KO_vs_F_F.bed"   = "#5b92cb",
  "K4me3_distal_CpG_plus_Double_KO_vs_F_F.bed"    = "#50c7ef",
  "K4me3_proximal_CpG_minus_Double_KO_vs_F_F.bed" = "#ed2c85",
  "K4me3_proximal_CpG_plus_Double_KO_vs_F_F.bed"  = "#ad2f93"
)

make_theme <- function(base_size = 11) {
  ggplot2::theme_classic(base_size = base_size) +
    theme(
      legend.text = element_text(size = 7),
      legend.title = element_blank(),
      axis.text = element_text(size = 7),
      axis.title = element_text(size = 8),
      plot.title = element_text(size = 9)
    )
}

find_distances <- function(class = "LINE", repeat_mask, peak_dir, add_info = FALSE) {
  pattern <- paste0("\\b(", class, "|", class, "?)\\b")
  repeat_mask_subset <- repeat_mask[grep(pattern, repeat_mask$V12), ]

  distances_list <- character(0)
  all_frames <- list()

  for (file_name in PEAK_FILES) {
    peak_path <- file.path(peak_dir, file_name)
    if (!file.exists(peak_path)) {
      warning(sprintf("Missing peak file: %s", peak_path))
      next
    }

    d <- read.table(peak_path, sep = "\t", header = FALSE)
    distances <- extractdistances(
      peaks.coords = d,
      repeat_mask_line = repeat_mask_subset,
      addfamily = TRUE,
      addpeaks = TRUE,
      addlines = TRUE,
      add5prime = TRUE
    )

    distances_list <- c(distances_list, file_name)
    assign(file_name, distances, envir = .GlobalEnv)

    pre <- data.frame(
      distance = as.numeric(as.character(distances[, 1])),
      group = file_name,
      class = class,
      stringsAsFactors = FALSE
    )

    if (add_info) {
      pre_add_info <- data.frame(
        peak_chr = as.character(distances[, 2]),
        peak_start = as.numeric(as.character(distances[, 3])),
        peak_end = as.numeric(as.character(distances[, 4])),
        line_chr = as.character(distances[, 6]),
        line_start = as.numeric(as.character(distances[, 7])),
        line_end = as.numeric(as.character(distances[, 8])),
        line_strand = as.character(distances[, 9]),
        family = as.character(distances[, 5]),
        stringsAsFactors = FALSE
      )
      pre <- cbind(pre, pre_add_info)
    }

    all_frames[[length(all_frames) + 1]] <- pre
  }

  if (length(all_frames) == 0) {
    return(data.frame())
  }

  do.call(rbind, all_frames)
}

make_ecdf_plot <- function(df, title, outfile) {
  p <- ggplot(df, aes(as.numeric(as.character(distance)), colour = group)) +
    stat_ecdf(geom = "step") +
    labs(title = title, y = "Fraction of peaks", x = "Distance to nearest TE (bp)") +
    scale_color_manual(values = te_group_colors) +
    make_theme() +
    theme(axis.line = element_line(color = "black"))
  ggsave(outfile, plot = p, width = 14, height = 10, units = "cm", device = "pdf")
}

run_wilcox_tests <- function(df, group_col = "class", value_col = "distance") {
  classes <- unique(df[[group_col]])
  kmatrix <- matrix(NA_real_, nrow = length(classes), ncol = length(classes))
  colnames(kmatrix) <- classes
  rownames(kmatrix) <- classes

  for (i in seq_along(classes)) {
    for (j in i:length(classes)) {
      a <- classes[i]
      b <- classes[j]
      va <- as.numeric(as.character(df[df[[group_col]] == a, value_col]))
      vb <- as.numeric(as.character(df[df[[group_col]] == b, value_col]))
      pval <- wilcox.test(va, vb)$p.value
      kmatrix[a, b] <- pval
      kmatrix[b, a] <- pval
    }
  }
  kmatrix
}

# ------------------------------ LOAD INPUTS ------------------------------
if (!dir.exists(OUTDIR)) dir.create(OUTDIR, recursive = TRUE, showWarnings = FALSE)

repeat_mask <- read.table(REPEATMASK_FILE, sep = "\t", header = FALSE)

# ------------------------------ RUN TE CLASS ANALYSES ------------------------------
classes_to_test <- c("LINE", "SINE", "LTR")

all_results <- list()
for (cls in classes_to_test) {
  df_cls <- find_distances(class = cls, repeat_mask = repeat_mask, peak_dir = PEAKS_DIR, add_info = TRUE)
  make_ecdf_plot(df_cls, title = paste(cls, "distance cumulative distribution"), outfile = file.path(OUTDIR, paste0(cls, "_cumulative_distribution.pdf")))
  all_results[[cls]] <- df_cls
}

# ERV subset (LTR entries with ERV in the repeat name)
pattern <- "\\b(LTR|LTR?)\\b"
repeat_mask_ltr <- repeat_mask[grep(pattern, repeat_mask$V12), ]
repeat_mask_erv <- repeat_mask_ltr[grepl("ERV", repeat_mask_ltr$V13), ]
df_erv <- find_distances(class = "LTR", repeat_mask = repeat_mask_erv, peak_dir = PEAKS_DIR, add_info = TRUE)
df_erv$class <- "ERV (LTR subset)"
make_ecdf_plot(df_erv, title = "ERV distance cumulative distribution", outfile = file.path(OUTDIR, "ERV_cumulative_distribution.pdf"))

# Combine selected classes for one merged plot
# Keep only the distal CpG minus group for the simplified comparison as in the old script.
selected_group <- "K4me3_distal_CpG_minus_Double_KO_vs_F_F.bed"
TE_dcm <- rbind(
  all_results[["LINE"]][all_results[["LINE"]]$group == selected_group, ],
  all_results[["SINE"]][all_results[["SINE"]]$group == selected_group, ],
  all_results[["LTR"]][all_results[["LTR"]]$group == selected_group, ],
  df_erv[df_erv$group == selected_group, ]
)

te_colors <- c(
  "LTR" = "#ed4b8e",
  "SINE" = "#5d93cc",
  "LINE" = "#50caf1",
  "ERV (LTR subset)" = "#b2469a"
)

TE_plot <- ggplot(TE_dcm, aes(x = as.numeric(as.character(distance)), colour = class)) +
  stat_ecdf(geom = "step", linewidth = 0.4) +
  scale_color_manual(values = te_colors) +
  labs(title = "TE distance cumulative distribution", y = "Fraction of peaks", x = "Distance from nearest TE (bp)") +
  make_theme() +
  theme(axis.line = element_line(color = "black"), legend.position = "right")

ggsave(file.path(OUTDIR, "TE_cumulative_distribution.pdf"), plot = TE_plot, width = 14, height = 10, units = "cm", device = "pdf")

# Wilcoxon p-values for TE classes
TE_classes <- unique(TE_dcm$class)
kmatrix_TE <- matrix(NA_real_, nrow = length(TE_classes), ncol = length(TE_classes))
colnames(kmatrix_TE) <- TE_classes
rownames(kmatrix_TE) <- TE_classes

for (i in seq_along(TE_classes)) {
  for (j in i:length(TE_classes)) {
    a <- TE_classes[i]
    b <- TE_classes[j]
    va <- as.numeric(as.character(TE_dcm[TE_dcm$class == a, "distance"]))
    vb <- as.numeric(as.character(TE_dcm[TE_dcm$class == b, "distance"]))
    pval <- wilcox.test(va, vb)$p.value
    kmatrix_TE[a, b] <- pval
    kmatrix_TE[b, a] <- pval
  }
}

write.table(kmatrix_TE, file = file.path(OUTDIR, "TE_cumulative_distribution_pval_wilcox.tsv"), col.names = TRUE, row.names = TRUE, quote = FALSE, sep = "\t")

cat("Done. Results written to:", OUTDIR, "\n")
